# ---------------------------------------------------------------- Part 2.4: Fairness trade-off
# Sensitive groups from part 2.1 on TEST set
test_sensitive = X_test[sensitive].values
group_a_mask_test = test_sensitive == group_a_name
group_b_mask_test = test_sensitive == group_b_name

thresholds = np.arange(0.05, 0.96, 0.10)  # 0.05, 0.15, ..., 0.95
fairness_rows = []
for t in thresholds:
    yhat = (prob_b_test >= t).astype(int)
    # Demographic Parity: P(yhat=1|A)/P(yhat=1|B)
    p_a = yhat[group_a_mask_test].mean() if group_a_mask_test.sum() > 0 else np.nan
    p_b = yhat[group_b_mask_test].mean() if group_b_mask_test.sum() > 0 else np.nan
    dp = p_a / p_b if (p_b and p_b > 0) else np.nan

    # Equalized Odds: min(TPR_A/TPR_B, FPR_A/FPR_B)
    def tpr_fpr(mask):
        m = yhat[mask]
        yt = y_test_arr[mask]
        tp = int(((m == 1) & (yt == 1)).sum())
        fn = int(((m == 0) & (yt == 1)).sum())
        fp = int(((m == 1) & (yt == 0)).sum())
        tn = int(((m == 0) & (yt == 0)).sum())
        tpr = tp / (tp + fn) if (tp + fn) > 0 else np.nan
        fpr = fp / (fp + tn) if (fp + tn) > 0 else np.nan
        return tpr, fpr

    tpr_a, fpr_a = tpr_fpr(group_a_mask_test)
    tpr_b, fpr_b = tpr_fpr(group_b_mask_test)
    eo_ratios = []
    if tpr_b and tpr_b > 0:
        eo_ratios.append(tpr_a / tpr_b)
    if fpr_b and fpr_b > 0:
        eo_ratios.append(fpr_a / fpr_b)
    eo = min(eo_ratios) if eo_ratios else np.nan

    # Predictive Parity: P(y=1|yhat=1, A) / P(y=1|yhat=1, B)
    pp_a = y_test_arr[group_a_mask_test & (yhat == 1)].mean() if (group_a_mask_test & (yhat == 1)).sum() > 0 else np.nan
    pp_b = y_test_arr[group_b_mask_test & (yhat == 1)].mean() if (group_b_mask_test & (yhat == 1)).sum() > 0 else np.nan
    pp = pp_a / pp_b if (pp_b and pp_b > 0) else np.nan

    acc = float((yhat == y_test_arr).mean())
    fairness_rows.append({
        "threshold": float(t),
        "DP": float(dp) if not np.isnan(dp) else None,
        "EO": float(eo) if not np.isnan(eo) else None,
        "PP": float(pp) if not np.isnan(pp) else None,
        "accuracy": acc,
        "p_hat_A": float(p_a),
        "p_hat_B": float(p_b),
        "tpr_A": float(tpr_a) if not np.isnan(tpr_a) else None,
        "tpr_B": float(tpr_b) if not np.isnan(tpr_b) else None,
        "fpr_A": float(fpr_a) if not np.isnan(fpr_a) else None,
        "fpr_B": float(fpr_b) if not np.isnan(fpr_b) else None,
        "pp_A": float(pp_a) if not np.isnan(pp_a) else None,
        "pp_B": float(pp_b) if not np.isnan(pp_b) else None,
        "n_A": int(group_a_mask_test.sum()),
        "n_B": int(group_b_mask_test.sum()),
    })

RESULTS["part24"] = {
    "sensitive": sensitive,
    "group_a": group_a_name,
    "group_b": group_b_name,
    "thresholds": [float(t) for t in thresholds],
    "rows": fairness_rows,
}
