def pick_two_groups(full_series, test_series):
    """Return two largest groups present in test with >=20 members each if possible."""
    vc = test_series.value_counts()
    cand = [g for g, c in vc.items() if c >= 20]
    if len(cand) >= 2:
        return cand[0], cand[1]
    # else two largest overall in full data
    vc_full = full_series.value_counts()
    return vc_full.index[0], vc_full.index[1]

